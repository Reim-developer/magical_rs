"""The :class:`FileKind` enum, one member per detectable file format,

and the :class:`Signature` that describes how each one is detected.

Generated by ``scripts/gen_kinds.ps1``. Do not edit by hand.

``Signature`` lives here rather than in ``_signatures`` because the two are
mutually recursive: a ``Signature`` names a ``FileKind``, and a ``FileKind``
has a ``rule`` that is a ``Signature``. Keeping them in one module is what
avoids an import cycle, and the alternative was a deferred import that a type
checker flags anyway. ``_signatures`` holds the functions that walk the
table and imports from here.
"""

from __future__ import annotations

import dataclasses
from enum import Enum
from typing import Final

from ._magical_rs import kind_matches, signature_of

__all__ = ["FileKind", "Signature"]

# The row the extension returns is spelled out at each unpacking site rather
# than aliased. A quoted module-level alias would be the obvious way to keep
# the two sites in step, but pyright does not accept a string as a type
# alias, and `typing.TypeAlias` is 3.10 while this package supports 3.8.
# `tests/test_stub.py` pins the extension against the stub, which is where
# the shape is actually asserted.


@dataclasses.dataclass(frozen=True)
class Signature:
    """One entry of the built-in detection table.

    Frozen because the table is a ``static`` in Rust and nothing here can
    change it: a caller that wants a different answer wants a level 2 rule,
    which is what :class:`~magical_py.MagicCustom` is for.
    """

    kind: FileKind
    signatures: tuple[bytes, ...]
    offsets: tuple[int, ...]
    max_bytes_read: int
    uses_predicate: bool

    @property
    def max_offset(self) -> int:
        """The furthest byte position this entry compares at.

        Zero for a predicate entry, whose rule decides on the buffer as a
        whole rather than at a position.
        """
        return max(self.offsets, default=0)

    def matches(self, data: bytes) -> bool:
        """Report whether *this* format's rule matches, ignoring the table.

        The one thing :func:`magical_py.detect` cannot tell you. Detection
        stops at the first entry that matched, so a format whose magic is
        also another format's is unreachable through it. A KTX2 file answers
        :func:`~magical_py.detect_bytes` with ``FileKind.Ktx2`` and this with
        ``True`` for ``FileKind.Ktx``, whose three magic bytes are a prefix
        of KTX2's.

        :param data: The leading bytes of a file.
        :returns: Whether this format's own rule would match them.
        """
        return kind_matches(self.kind.name, data)

    @classmethod
    def _from_row(cls, row: tuple[str, list[bytes], list[int], int, bool]) -> Signature:
        kind, signatures, offsets, max_bytes_read, uses_predicate = row
        return cls(
            kind=FileKind[kind],
            signatures=tuple(signatures),
            offsets=tuple(offsets),
            max_bytes_read=max_bytes_read,
            uses_predicate=uses_predicate,
        )


class FileKind(Enum):
    """A file format that ``magical_rs`` can detect.

    Members are named after the Rust ``FileKind`` variants, so a name that
    appears in the ``magical_rs`` documentation appears here too. The
    :attr:`value` of each member is a short, stable identifier intended for
    serialisation; use :attr:`mime` when you need a media type.

    Detect a format with :func:`magical_py.detect` or
    :func:`magical_py.detect_bytes`.
    """

    @classmethod
    def from_value(cls, value: str) -> FileKind:
        """Look a member up by its serialised value.

        :param value: A member :attr:`value`, such as ``"png"``.
        :returns: The matching member.
        :raises ValueError: If no member has that value.
        """
        return cls(value)

    @property
    def description(self) -> str:
        """A human-readable name for the format, such as ``"PNG"``."""
        return _META[self.name][0]

    @property
    def mime(self) -> str | None:
        """The registered media type, or ``None`` if there is none.

        ``None`` means no media type is registered or verified for this
        format. It never means "unknown", which would be a guess.
        """
        return _META[self.name][1]

    @property
    def extension(self) -> str | None:
        """The conventional file extension, or ``None`` if there is none.

        The extension carries no leading dot. It is advisory: detection
        never looks at the file name.
        """
        return _META[self.name][2]

    @property
    def rule(self) -> Signature:
        """The table entry that detects this format.

        What the format is matched on: the bytes, the offsets they are
        compared at, and the read size the entry declares. A format
        decided by a function rather than a fixed pattern reports
        ``uses_predicate`` and no signatures.

        :raises ValueError: If no signature produces this format, which
            would mean the enum and the table had drifted apart.
        """
        entry = signature_of(self.name)
        if entry is None:
            raise ValueError(
                f"{self.name} is not a format the detection table produces"
            )
        return Signature._from_row(entry)

    def matches(self, data: bytes) -> bool:
        """Report whether this format's own rule matches ``data``.

        :func:`magical_py.detect` stops at the first table entry that
        matched, so a format whose magic is also another format's is
        unreachable through it. This asks only about this one.

        :param data: The leading bytes of a file.
        :returns: Whether this format's own rule would match them.
        """
        return kind_matches(self.name, data)

