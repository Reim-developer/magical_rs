# ``enum`` ignores a string literal written after a member, so without this
# ``FileKind.Png.__doc__`` would fall back to the class docstring and
# ``help(FileKind)`` would list a hundred and fourteen identical paragraphs.
# Assigning it explicitly is what makes the display names show up there.
for _name, _meta in _META.items():
    setattr(FileKind[_name], "__doc__", _meta[0])
